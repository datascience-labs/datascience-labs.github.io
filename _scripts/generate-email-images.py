"""Render email labels as PNGs. Run with Python and Pillow installed."""

import hashlib
import re
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "images" / "email"
FONT_PATH = "C:/Windows/Fonts/arial.ttf"


def main():
    addresses = set()
    for path in (ROOT / "team" / "_posts").glob("*.md"):
        match = re.search(r"^email\s*:\s*(\S+)", path.read_text(encoding="utf-8"), re.M)
        if match:
            addresses.add(match[1])
    for path in (ROOT / "misc" / "_posts").glob("*.md"):
        addresses.update(re.findall(r'mailto:([^"\s]+)', path.read_text(encoding="utf-8")))

    OUTPUT.mkdir(parents=True, exist_ok=True)
    font = ImageFont.truetype(FONT_PATH, 48)
    mapping = ["# Generated by _scripts/generate-email-images.py"]
    for address in sorted(addresses):
        filename = hashlib.sha256(address.encode()).hexdigest()[:16] + ".png"
        bounds = font.getbbox(address)
        image = Image.new("RGB", (bounds[2] - bounds[0] + 12, 60), "white")
        ImageDraw.Draw(image).text((6 - bounds[0], 5 - bounds[1]), address, font=font, fill="black")
        image.save(OUTPUT / filename, optimize=True)
        mapping.append(f'"{address}": "/images/email/{filename}"')
    (ROOT / "_data" / "email_images.yml").write_text("\n".join(mapping) + "\n", encoding="utf-8")
    print(f"Generated {len(addresses)} email images.")


if __name__ == "__main__":
    main()
